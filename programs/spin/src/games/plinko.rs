//! Plinko: one bit of randomness per row decides left/right; the bucket is
//! the number of right turns and pays from a fixed table.

use crate::error::SpinError;
use crate::games::{payout, Eval};
use anchor_lang::prelude::*;

pub const RISK_LOW: u8 = 0;
pub const RISK_MED: u8 = 1;
pub const RISK_HIGH: u8 = 2;

pub const MIN_ROWS: u8 = 8;
pub const MAX_ROWS: u8 = 16;

