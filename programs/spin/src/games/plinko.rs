/// Returns the multiplier in basis points (10,000 = 1×) for a Plinko
/// (rows, risk, bucket) tuple, or 0 if the combination is invalid.
pub fn multiplier_bp(rows: u8, risk: u8, bucket: u8) -> u64 {
    if bucket > rows || risk > RISK_HIGH || rows < MIN_ROWS || rows > MAX_ROWS {
        return 0;
    }
    let table = TABLES_0_01[((rows - MIN_ROWS) * 3 + risk) as usize];
    table[bucket as usize] * 100
}

/// Encodes rows and risk into the `target` field: `target = (rows << 8) | risk`.
pub fn encode_target(rows: u8, risk: u8) -> u64 {
    ((rows as u64) << 8) | (risk as u64)
}

/// Decodes `target` back to (rows, risk); `None` if out of range or if any
/// stray bits are set.
pub fn decode_target(target: u64) -> Option<(u8, u8)> {
    if target >> 16 != 0 {
        return None;
    }
    let rows = ((target >> 8) & 0xFF) as u8;
    let risk = (target & 0xFF) as u8;
    if !(MIN_ROWS..=MAX_ROWS).contains(&rows) || risk > RISK_HIGH {
        return None;
    }
    Some((rows, risk))
}

pub fn validate_target(target: u64) -> Result<()> {
    decode_target(target)
        .map(|_| ())
        .ok_or_else(|| SpinError::InvalidTarget.into())
}

/// The table's edge bucket is its maximum.
pub fn max_multiplier_bp(target: u64) -> Result<u64> {
    let (rows, risk) = decode_target(target).ok_or(SpinError::InvalidTarget)?;
    Ok(multiplier_bp(rows, risk, 0))
}

/// Bit `i` of the randomness decides row `i`: 1 = right. `roll` = bucket.
pub fn evaluate(randomness: &[u8; 64], amount: u64, target: u64) -> Result<Eval> {
    let (rows, risk) = decode_target(target).ok_or(SpinError::InvalidTarget)?;
    let mut rights = 0u8;
    for i in 0..rows {
        if randomness[(i / 8) as usize] & (1 << (i % 8)) != 0 {
            rights += 1;
        }
    }
    let multiplier_bp = multiplier_bp(rows, risk, rights);
    Ok(Eval {
        roll: rights as u64,
        multiplier_bp,
        payout: payout(amount, multiplier_bp)?,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_symmetric_and_shaped_by_risk() {
        for rows in MIN_ROWS..=MAX_ROWS {
            for risk in RISK_LOW..=RISK_HIGH {
                for k in 0..=rows {
                    assert_eq!(
                        multiplier_bp(rows, risk, k),
                        multiplier_bp(rows, risk, rows - k),
                        "symmetric {rows}/{risk}/{k}"
                    );
                }
            }
            // Risk is volatility, not RTP: higher risk pays more at the edge
            // and less in the centre.
            assert!(multiplier_bp(rows, RISK_HIGH, 0) > multiplier_bp(rows, RISK_MED, 0));
            assert!(multiplier_bp(rows, RISK_MED, 0) > multiplier_bp(rows, RISK_LOW, 0));
            assert!(multiplier_bp(rows, RISK_HIGH, rows / 2) < multiplier_bp(rows, RISK_LOW, rows / 2));
        }
    }

    #[test]
    fn rtp_is_about_97_percent() {
        // Σ C(n,k)/2^n · mult_k, in integer arithmetic scaled by 2^n·10_000.
        for rows in MIN_ROWS..=MAX_ROWS {
            for risk in RISK_LOW..=RISK_HIGH {
                let mut num: u128 = 0;
                let mut c: u128 = 1;
                for k in 0..=rows {
                    num += c * multiplier_bp(rows, risk, k) as u128;
                    c = c * (rows - k) as u128 / (k as u128 + 1);
                }
                let rtp_bp = num / (1u128 << rows); // bp
                assert!((9_600..=9_760).contains(&rtp_bp), "rtp {rows}/{risk} = {rtp_bp} bp");
            }
        }
    }

    #[test]
    fn bounds_and_targets() {
        assert_eq!(multiplier_bp(12, 99, 0), 0);
        assert_eq!(multiplier_bp(7, RISK_LOW, 0), 0);
        assert_eq!(multiplier_bp(17, RISK_LOW, 0), 0);
        assert_eq!(multiplier_bp(12, RISK_LOW, 13), 0);
        assert_eq!(multiplier_bp(8, RISK_LOW, 0), 50_400);
        assert_eq!(multiplier_bp(8, RISK_LOW, 4), 7_400);

        let t = encode_target(12, RISK_HIGH);
        assert_eq!(decode_target(t), Some((12, RISK_HIGH)));
        assert_eq!(decode_target(encode_target(8, RISK_LOW)), Some((8, RISK_LOW)));
        assert_eq!(decode_target(encode_target(16, RISK_MED)), Some((16, RISK_MED)));
        assert_eq!(decode_target(0xFF), None);
        assert_eq!(decode_target(0x05 << 8), None);
        assert_eq!(decode_target((1 << 16) | encode_target(8, RISK_LOW)), None);
        assert!(validate_target(0).is_err());
        assert_eq!(max_multiplier_bp(encode_target(16, RISK_HIGH)).unwrap(), 9_209_200);
    }

    #[test]
    fn eval_counts_right_turns() {
        let target = encode_target(8, RISK_LOW);
        let zero = [0u8; 64];
        let o = evaluate(&zero, 1_000_000, target).unwrap();
        assert_eq!(o.roll, 0);
        assert_eq!(o.multiplier_bp, multiplier_bp(8, RISK_LOW, 0));
        assert_eq!(o.payout, 5_040_000);

        let mut r = [0u8; 64];
        r[0] = 0b0000_1111; // rows 0..3 right
        let o = evaluate(&r, 1_000_000, target).unwrap();
        assert_eq!(o.roll, 4);
        assert_eq!(o.payout, 740_000);
        // 16 rows reads two bytes.
        let mut r = [0u8; 64];
        r[0] = 0xFF;
        r[1] = 0xFF;
        let o = evaluate(&r, 10, encode_target(16, RISK_HIGH)).unwrap();
        assert_eq!(o.roll, 16);
    }
}
